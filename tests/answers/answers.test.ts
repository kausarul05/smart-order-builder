describe('Q5 to Q8 - the six seed orders, priced with our own engine', () => {
  const orders = priceSeedOrders(seed, menu);

  it('Q5 - payable per order and the total', () => {
    for (const order of orders) {
      say(
        `Q5  ${order.id}  ${order.createdAt}  ${order.paymentMethod}` +
          `  subtotal ${formatPoisha(order.totals.subtotal)}` +
          `  discount ${order.totals.discount?.id ?? 'none'} ${formatPoisha(order.totals.discount?.amount ?? 0)}` +
          `  VAT ${formatPoisha(order.totals.vat)}` +
          `  payable ${formatPoisha(order.totals.payable)}`,
      );
    }
    say(`Q5  total revenue = ${formatPoisha(totalRevenue(orders))} BDT`);

    expect(orders).toHaveLength(6);
    for (const order of orders) expect(order.totals.payable % 100).toBe(0);
  });

  it('Q6 - the best-selling option by units', () => {
    const ranked = optionUnitsSold(orders, menu);
    say(
      `Q6  ${ranked
        .slice(0, 5)
        .map((entry) => `${entry.name} ${entry.units}`)
        .join(', ')}`,
    );
    const best = bestSellingOption(orders, menu);
    expect(best).not.toBeNull();
    say(`Q6  best seller = ${best?.name} with ${best?.units} units`);
  });

  it('Q7 - the payment method with the most revenue', () => {
    const byMethod = revenueByPaymentMethod(orders);
    for (const [method, revenue] of Object.entries(byMethod)) {
      say(`Q7  ${method} = ${formatPoisha(revenue ?? 0)} BDT`);
    }
    const top = topPaymentMethod(orders);
    say(`Q7  top = ${top?.method} with ${formatPoisha(top?.revenue ?? 0)} BDT`);
    expect(top).not.toBeNull();
  });

  it('Q8 - how many seed orders actually received MORNING15', () => {
    const applied = ordersWithCouponApplied(orders);
    const rejected = ordersWithCouponRejected(orders);

    say(`Q8  coupon actually applied to ${applied.length} orders:`);
    for (const order of applied) {
      say(
        `Q8    ${order.id} got ${formatPoisha(order.totals.discount?.amount ?? 0)} BDT off`,
      );
    }
    say(`Q8  carried a code but got no discount: ${rejected.length}`);
    for (const { order, reason } of rejected) {
      say(`Q8    ${order.id} - ${reason}`);
    }

    const withCode = orders.filter((order) => order.coupon.entered !== null);
    expect(applied.length + rejected.length).toBe(withCode.length);
  });
});

/* ------------------------------------------------------------- helpers */

function unitCeilingFor(groupId: string): number {
  // A ceiling per group that is generous enough to contain the optimum
  // while keeping the brute force small.
  if (groupId === 'eggs') return 6;
  if (groupId === 'protein') return 3;
  if (groupId === 'extras') return 2;
  if (groupId === 'sauce') return 1;
  return 1;
}

/** Every way to spread 0..ceiling units across `optionIds`. */
function enumerateGroup(
  optionIds: readonly string[],
  ceiling: number,
): readonly Record<string, number>[] {
  const out: Record<string, number>[] = [];
  const walk = (index: number, remaining: number, acc: Record<string, number>): void => {
    if (index === optionIds.length) {
      out.push({ ...acc });
      return;
    }
    const id = optionIds[index];
    if (id === undefined) return;
    for (let units = 0; units <= remaining; units += 1) {
      const next = { ...acc };
      if (units > 0) next[id] = units;
      walk(index + 1, remaining - units, next);
    }
  };
  walk(0, ceiling, {});
  return out;
}

function* cartesian<T>(lists: readonly (readonly T[])[]): Generator<readonly T[]> {
  if (lists.length === 0) {
    yield [];
    return;
  }
  const [head, ...rest] = lists;
  for (const item of head ?? []) {
    for (const tail of cartesian(rest)) yield [item, ...tail];
  }
}

