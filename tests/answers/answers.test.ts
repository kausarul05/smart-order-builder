const emptySnapshot: StockSnapshot = {
  onHand: DEFAULT_STOCK,
  reserved: {},
  sold: {},
};

describe('Q1 - how many of item C fit in an empty cart?', () => {
  it('is 2, limited by cheese', () => {
    const available = availableMap(emptySnapshot, menu.ingredients);
    const perUnit = lineAllocation(SELECTION_C, menu.groups, 1);

    // Largest n with perUnit x n <= available for every ingredient.
    const limits = Object.entries(perUnit).map(([id, need]) => ({
      id,
      max: Math.floor((available[id] ?? 0) / need),
    }));
    limits.sort((a, b) => a.max - b.max);
    const answer = limits[0];

    say(`Q1  max units of C = ${answer?.max}, limited by ${answer?.id}`);
    say(
      `    headroom per ingredient: ${limits
        .map((limit) => `${limit.id} ${limit.max}`)
        .join(', ')}`,
    );

    expect(answer?.max).toBe(2);
    expect(answer?.id).toBe('cheese');
  });
});

describe('Q2 - the cheapest valid configuration', () => {
  it('is Toast + Fried x2 + Tofu at 360.00 BDT', () => {
    // Brute force over every combination that could possibly be cheapest:
    // at most 6 units in eggs, 3 in protein, 4 in extras, 2 in sauce.
    let best: { selection: Selection; price: number } | null = null;

    const groupChoices = menu.groups.map((group) =>
      enumerateGroup(group.options.map((option) => option.id), unitCeilingFor(group.id)),
    );

    for (const combo of cartesian(groupChoices)) {
      const selection: Record<string, number> = {};
      for (const part of combo) Object.assign(selection, part);
      if (validate(configOf(selection), menu.groups, menu.rules).length > 0) continue;
      const price = priceUnit(selection, menu).unitPrice;
      if (best === null || price < best.price) best = { selection, price };
    }

    say(`Q2  cheapest valid unit price = ${formatPoisha(best?.price ?? 0)} BDT`);
    say(`    selection: ${JSON.stringify(best?.selection)}`);

    expect(best?.price).toBe(bdt(360));
  });
});

describe('Q3 - cart A x3 at 10:30 and again at 11:30', () => {
  it('reports both, with MORNING15 entered', () => {
    const cart = [{ selection: SELECTION_A, qty: 3 }];

    for (const [label, serverTime] of [
      ['10:30', AT_1030],
      ['11:30', AT_1130],
    ] as const) {
      const breakdown = priceCart({
        cart,
        menu,
        couponCode: 'MORNING15',
        serverTime,
      });
      say(
        `Q3  ${label}  subtotal ${formatPoisha(breakdown.subtotal)}` +
          `  discount ${breakdown.discount?.id ?? 'none'} ${formatPoisha(breakdown.discount?.amount ?? 0)}` +
          `  VAT ${formatPoisha(breakdown.vat)}` +
          `  payable ${formatPoisha(breakdown.payable)}`,
      );
    }

    const morning = priceCart({ cart, menu, couponCode: 'MORNING15', serverTime: AT_1030 });
    expect(morning.subtotal).toBe(bdt(1140));
    expect(morning.discount?.id).toBe('C2');
    expect(morning.discount?.amount).toBe(bdt(150));
    expect(morning.vat).toBe(bdt(49.5));
    expect(morning.payable).toBe(bdt(1040));

    const later = priceCart({ cart, menu, couponCode: 'MORNING15', serverTime: AT_1130 });
    expect(later.discount).toBeNull(); // 1,140.00 never reaches the 1,200.00 C1 threshold
    expect(later.vat).toBe(bdt(57));
    expect(later.payable).toBe(bdt(1197));
  });
});

